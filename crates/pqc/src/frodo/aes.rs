const RCON: [u8; 11] = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36,
];

fn xtime(x: u8) -> u8 {
    // Multiply by x in GF(2^8) with the FIPS-197 polynomial.
    (x << 1) ^ (((x >> 7) & 1) * 0x1B)
}

/// Expand a 128-bit key into the 11 round keys (44 words, big-endian bytes).
fn key_expansion(key: &[u8; 16]) -> [[u8; 4]; 44] {
    let mut w = [[0u8; 4]; 44];
    for (i, word) in w.iter_mut().take(4).enumerate() {
        *word = [key[4 * i], key[4 * i + 1], key[4 * i + 2], key[4 * i + 3]];
    }
    for i in 4..44 {
        let mut temp = w[i - 1];
        if i % 4 == 0 {
            temp = [
                SBOX[temp[1] as usize],
                SBOX[temp[2] as usize],
                SBOX[temp[3] as usize],
                SBOX[temp[0] as usize],
            ];
            temp[0] ^= RCON[i / 4];
        }
        for j in 0..4 {
            w[i][j] = w[i - 4][j] ^ temp[j];
        }
    }
    w
}

fn add_round_key(state: &mut [u8; 16], w: &[[u8; 4]; 44], round: usize) {
    for col in 0..4 {
        for row in 0..4 {
            state[4 * col + row] ^= w[4 * round + col][row];
        }
    }
}

fn sub_bytes(state: &mut [u8; 16]) {
    for b in state.iter_mut() {
        *b = SBOX[*b as usize];
    }
}

fn shift_rows(state: &mut [u8; 16]) {
    // State is column-major: state[r + 4c]; row r is rotated left by r.
    let old = *state;
    for r in 1..4 {
        for c in 0..4 {
            state[r + 4 * c] = old[r + 4 * ((c + r) % 4)];
        }
    }
}

fn mix_columns(state: &mut [u8; 16]) {
    for c in 0..4 {
        let col = [
            state[4 * c],
            state[4 * c + 1],
            state[4 * c + 2],
            state[4 * c + 3],
        ];
        let mut dbl = [0u8; 4];
        for (i, &v) in col.iter().enumerate() {
            dbl[i] = xtime(v);
        }
        state[4 * c] = dbl[0] ^ xtime(col[1]) ^ col[1] ^ col[2] ^ col[3];
        state[4 * c + 1] = col[0] ^ dbl[1] ^ xtime(col[2]) ^ col[2] ^ col[3];
        state[4 * c + 2] = col[0] ^ col[1] ^ dbl[2] ^ xtime(col[3]) ^ col[3];
        state[4 * c + 3] = xtime(col[0]) ^ col[0] ^ col[1] ^ col[2] ^ dbl[3];
    }
}

/// AES-128 encryption of one 16-byte block (FIPS-197, Cipher).
pub fn encrypt_block(key: &[u8; 16], block: &[u8; 16]) -> [u8; 16] {
    let w = key_expansion(key);
    let mut state = *block;
    add_round_key(&mut state, &w, 0);
    for round in 1..10 {
        sub_bytes(&mut state);
        shift_rows(&mut state);
        mix_columns(&mut state);
        add_round_key(&mut state, &w, round);
    }
    sub_bytes(&mut state);
    shift_rows(&mut state);
    add_round_key(&mut state, &w, 10);
    state
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fmt::Write as _;

    fn hex(b: &[u8]) -> String {
        b.iter().fold(String::new(), |mut s, x| {
            let _ = write!(s, "{:02x}", x);
            s
        })
    }

    /// FIPS-197 Appendix C.1 (AES-128) and Appendix B worked example.
    #[test]
    fn fips197_vectors() {
        // FIPS-197 Appendix C.1: AES-128.
        let pt = [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB, 0xCC, 0xDD,
            0xEE, 0xFF,
        ];
        let key = [
            0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D,
            0x0E, 0x0F,
        ];
        assert_eq!(
            hex(&encrypt_block(&key, &pt)),
            "69c4e0d86a7b0430d8cdb78070b4c55a"
        );

        // NIST SP 800-38A F.1.1 AES-128-ECB vector 1.
        let key = [
            0x2B, 0x7E, 0x15, 0x16, 0x28, 0xAE, 0xD2, 0xA6, 0xAB, 0xF7, 0x15, 0x88, 0x09, 0xCF,
            0x4F, 0x3C,
        ];
        let pt = [
            0x6B, 0xC1, 0xBE, 0xE2, 0x2E, 0x40, 0x9F, 0x96, 0xE9, 0x3D, 0x7E, 0x11, 0x73, 0x93,
            0x17, 0x2A,
        ];
        assert_eq!(
            hex(&encrypt_block(&key, &pt)),
            "3ad77bb40d7a3660a89ecaf32466ef97"
        );
    }
}
